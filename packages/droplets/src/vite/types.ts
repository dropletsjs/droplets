import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import type { DropletEntry } from "../core/discover.ts";
import { logger } from "../core/logger.ts";
import { SCRIPT_RENDERER, type DropletRenderer } from "../renderer.ts";

/** Where `./$types` live, next to the project's `tsconfig.json`: `.droplets/`. */
export const TYPES_DIR = ".droplets";

/** The name a droplet's files import their types from: `import type { Data } from "./$types"`. */
const TYPES_FILE = "$types.d.ts";

const HEADER = "// Generated by droplets (vite, or `djs sync`): do not edit.";

const posix = (path: string) => path.split(sep).join("/");

/** `./x` or `../x`: a relative specifier from `from` (a directory) to `to`. */
function specifier(from: string, to: string): string {
  const path = posix(relative(from, to));
  return path.startsWith(".") ? path : `./${path}`;
}

/**
 * A droplet's `$types.d.ts`. Every type comes from the droplet's own files:
 * the props from the `props` schema in `+droplet.ts`, the data from what its
 * loads return, so the component is typed by the server load it never sees.
 */
export function dropletTypesCode(
  entry: DropletEntry,
  renderer: DropletRenderer | undefined,
  typesFile: string,
  folder: string,
  label = posix(folder),
): string {
  const from = dirname(typesFile);
  const module = (file: string) => `typeof import(${JSON.stringify(specifier(from, join(folder, file)))})`;
  const componentTypes = renderer?.componentTypes ?? "@dropletsjs/droplets";
  const script = entry.renderer === SCRIPT_RENDERER;
  const scriptTypes = script
    ? [
      "/** The default export of `+droplet.script.ts`: `(data, el)`, run in the browser; it may return a cleanup. */",
      "export type DropletScript = BaseDropletScript<Data>;",
      "",
    ]
    : [];
  return [
    HEADER,
    `// ${label}/ (${entry.renderer})`,
    'import type { ActionEvent as BaseActionEvent, ActionFailure, DropletLoadEvent as BaseDropletLoadEvent, LoadEvent as BaseLoadEvent } from "@dropletsjs/droplets/server";',
    'import type { InferSchemaOutput } from "@dropletsjs/droplets";',
    `import type { DropletErrorProps as ComponentErrorProps, DropletProps as ComponentProps } from ${JSON.stringify(componentTypes)};`,
    ...(script ? ['import type { DropletScript as BaseDropletScript } from "@dropletsjs/droplets";'] : []),
    "",
    `type Universal = ${entry.hasLoad ? module("+droplet.ts") : "{}"};`,
    `type Server = ${entry.hasServerLoad ? module("+droplet.server.ts") : "{}"};`,
    "type Returned<M, K extends string> = M extends { [key in K]: (...args: any[]) => infer R } ? Awaited<R> : never;",
    "type Handled<M, R = Returned<M, \"handleError\">> = [R] extends [never] ? never : R extends { error: infer E } ? E : never;",
    "type ActionsOf<M> = M extends { actions: infer A } ? A : never;",
    "type Outcome<R> = R extends ActionFailure<infer D> ? D : R extends void ? undefined : R;",
    "",
    "/** The caller's props, after the `props` schema in `+droplet.ts`. */",
    "export type Props = Universal extends { props: infer Schema } ? InferSchemaOutput<Schema> : Record<string, unknown>;",
    "/** What `load` in `+droplet.server.ts` returns; `undefined` without one. */",
    "export type ServerData = [Returned<Server, \"load\">] extends [never] ? undefined : Returned<Server, \"load\">;",
    "/** What the component gets as `data`: the universal load's result, else the server load's. */",
    "export type Data = [Returned<Universal, \"load\">] extends [never] ? ServerData : Returned<Universal, \"load\">;",
    "/** What the error page gets as `error`: `handleError`'s, else whatever was thrown. */",
    "export type ErrorData = [Handled<Server> | Handled<Universal>] extends [never] ? unknown : Handled<Server> | Handled<Universal>;",
    "",
    "/** The event of `load` in `+droplet.server.ts`. */",
    "export type LoadEvent = Omit<BaseLoadEvent, \"props\"> & { props: Props };",
    "/** The event of `load` in `+droplet.ts`. */",
    "export type DropletLoadEvent = Omit<BaseDropletLoadEvent, \"props\" | \"data\"> & { props: Props; data: ServerData };",
    "/** For `satisfies ServerLoad`; annotate the parameter instead (`(event: LoadEvent)`) to keep `Data` exact. */",
    "export type ServerLoad<Out = unknown> = (event: LoadEvent) => Out | Promise<Out>;",
    "/** For `satisfies Load`, as `ServerLoad`. */",
    "export type Load<Out = unknown> = (event: DropletLoadEvent) => Out | Promise<Out>;",
    "",
    "/** The event of a form action in `+droplet.server.ts`. */",
    "export type ActionEvent = Omit<BaseActionEvent, \"props\"> & { props: Props };",
    "/** For `export const actions = { … } satisfies Actions`. */",
    "export type Actions = Record<string, (event: ActionEvent) => unknown>;",
    "/**",
    " * Each action `actions` exports, by name, with what `form` gets after it: what it returned, or its",
    " * `fail()` data. For `actionUrl<DropletActions>()` and the enhance helpers of `$droplets/form`.",
    " */",
    "export type DropletActions = [ActionsOf<Server>] extends [never] ? {} : { [K in keyof ActionsOf<Server> & string]: ActionsOf<Server>[K] extends (...args: any[]) => infer R ? Outcome<Awaited<R>> : never };",
    "/** What the component gets as `form` after an action: what it returned, or its `fail()` data. */",
    "export type ActionData = [ActionsOf<Server>] extends [never] ? undefined : DropletActions[keyof DropletActions] | undefined;",
    "",
    "/** The component's props. */",
    "export type DropletProps = ComponentProps<Data> & { form?: ActionData };",
    "/** The error page's props. */",
    "export type DropletErrorProps = ComponentErrorProps<ErrorData>;",
    "",
    ...scriptTypes,
  ].join("\n");
}

/**
 * `.droplets/tsconfig.json`: the project's tsconfig extends it so `./$types`
 * resolve. It is also the nearest tsconfig of the generated files, which
 * Vue's compiler reads to resolve the packages they import
 * (`defineProps<DropletProps>()`): Vite's resolution, so `exports` count.
 */
export function typesTsconfig(root: string, typesRoot: string): string {
  const dir = resolve(root, TYPES_DIR);
  return `${JSON.stringify(
    {
      compilerOptions: {
        module: "esnext",
        moduleResolution: "bundler",
        rootDirs: [specifier(dir, root), specifier(dir, typesRoot)],
      },
    },
    null,
    2,
  )}\n`;
}

/**
 * Writes `.droplets/tsconfig.json` when it is missing. The project's
 * tsconfig extends it and Vite's transforms read that tsconfig, so on a
 * fresh checkout (no `.droplets/` yet) loading the config would fail before
 * anything could write it.
 */
export async function ensureTypesTsconfig(root: string): Promise<void> {
  const path = resolve(root, TYPES_DIR, "tsconfig.json");
  if (await readFile(path).then(() => true, () => false)) return;
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, typesTsconfig(root, resolve(root, TYPES_DIR, "types")));
}

type SyncInput = {
  root: string;
  dropletsRoot: string;
  entries: DropletEntry[];
  renderers: DropletRenderer[];
};

async function writeIfChanged(path: string, code: string): Promise<boolean> {
  const current = await readFile(path, "utf8").catch(() => null);
  if (current === code) return false;
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, code);
  return true;
}

async function listGenerated(dir: string): Promise<string[]> {
  const found: string[] = [];
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await listGenerated(path)));
    else if (entry.name === TYPES_FILE) found.push(path);
  }
  return found;
}

/**
 * Writes `.droplets/`: a `$types.d.ts` per droplet, mirroring its folder, and
 * the tsconfig that maps them next to the droplets. Files that would not
 * change are left alone; those of droplets that are gone are removed.
 */
export async function syncDropletTypes(input: SyncInput): Promise<{ written: string[] }> {
  const typesRoot = resolve(input.root, TYPES_DIR, "types");
  const byName = new Map(input.renderers.map((renderer) => [renderer.name, renderer]));
  const written: string[] = [];
  const wanted = new Set<string>();

  for (const entry of input.entries) {
    const folder = resolve(input.dropletsRoot, entry.name);
    const file = resolve(typesRoot, relative(input.root, folder), TYPES_FILE);
    wanted.add(file);
    const code = dropletTypesCode(entry, byName.get(entry.renderer), file, folder, posix(relative(input.root, folder)));
    if (await writeIfChanged(file, code)) {
      written.push(file);
    }
  }
  const tsconfig = resolve(input.root, TYPES_DIR, "tsconfig.json");
  if (await writeIfChanged(tsconfig, typesTsconfig(input.root, typesRoot))) written.push(tsconfig);

  for (const stale of await listGenerated(typesRoot)) {
    if (!wanted.has(stale)) await rm(stale);
  }
  return { written };
}

/**
 * `./$types` for the droplets the plugin knows now. A failure to write them
 * (a read-only checkout) is reported and stops neither the dev server nor
 * the build.
 */
export async function syncTypes(input: SyncInput): Promise<void> {
  try {
    await syncDropletTypes(input);
  } catch (error) {
    logger.warn("framework", `could not write ${TYPES_DIR}/: ${error instanceof Error ? error.message : String(error)}`);
  }
}
