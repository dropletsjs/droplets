/**
 * AGENTS.md: what a coding agent needs to work in the project, first the
 * rule that keeps droplets in one framework each. Written for the project's
 * frameworks, adapters and package manager.
 */
import { ADAPTERS, commands, defaultAdapter, starterName, type Choices } from "./choices.ts";
import type { Framework } from "./shared.ts";

const FLAGS_WHERE: Record<Framework["name"], string> = {
  svelte: "`<script module>`: `export const hydrate = true;`",
  vue: "a plain `<script>` next to `<script setup>`: `export const hydrate = true;`",
  react: "named exports of the component file: `export const hydrate = true;`",
  preact: "named exports of the component file: `export const hydrate = true;`",
  solid: "named exports of the component file: `export const hydrate = true;`",
  "hono-jsx": "named exports of the component file: `export const hydrate = true;`",
  handlebars: "the comment the template opens with: `{{!-- export hydrate = true --}}`",
  lit: "named exports of the component file: `export const hydrate = true;`",
  script: "named exports of `+droplet.script.ts`: `export const hydrate = \"visible\";` (no `ssr`)",
};

const STYLES_WHERE: Record<Framework["name"], string> = {
  svelte: "a `<style>` block",
  vue: "a `<style>` block (`scoped` works)",
  react: "`import \"./style.css\"` in the component",
  preact: "`import \"./style.css\"` in the component",
  solid: "`import \"./style.css\"` in the component",
  "hono-jsx": "`import \"./style.css\"` in the component",
  handlebars: "a `<style>` block, inline or `<style src=\"./x.css\"></style>`, at the top of the template",
  lit: "`static styles`, with Lit's `css` tag, in the class: the component renders in a shadow root, which page and droplet stylesheets never reach (CSS custom properties do)",
  script: "`import \"./style.css\"` in the script",
};

export function agentsMd(choices: Choices): string {
  const { run, djs } = commands(choices.pm);
  const main = defaultAdapter(choices.adapters);
  const frameworks = choices.frameworks.map((f) => f.label).join(", ");
  const adapters = ADAPTERS.filter((a) => choices.adapters.includes(a.value)).map((a) => a.value);
  const jsx = choices.frameworks.filter((f) => f.jsxImportSource);
  const example = choices.frameworks[0]!;
  const lines: string[] = [
    "# AGENTS.md",
    "",
    "A [Droplets](https://dropletsjs.dev) project: server-rendered components that",
    "any page can embed. Each droplet is one component with its own URL,",
    "`/droplets/<id>`, served by a small Hono server that Vite builds.",
    "",
    `Frameworks: ${frameworks}. Adapters: ${adapters.join(", ")} (\`vite build\` targets ${main}).`,
    "",
    "## The first rule: one framework per droplet",
    "",
    "**Always import only the droplet's own framework in its code.** When",
    "something must work across frameworks, move it into a framework-agnostic",
    "folder (e.g. `src/lib/`) and keep it neutral.",
    "",
    "```",
    "src/lib/api.ts           neutral: no framework imports; any droplet may use it",
    "src/lib/react/Card.tsx   React's own: only React droplets import it",
    "```",
    "",
    "A droplet that reaches another framework's files (`.svelte`, `.vue`, …) or",
    "packages (`svelte`, `vue`, `react`, `preact`, `solid-js`, `hono/jsx`, `lit`, …), directly or",
    "through what it imports, fails `vite build` and shows as an error in",
    "`vite dev`; the message names the import chain. Fix it by moving the shared",
    "part into neutral code, never by importing across.",
    ...(jsx.length > 1
      ? [
          "",
          `${jsx.map((f) => f.label).join(", ")} all use \`.tsx\`: start every \`.tsx\` file with`,
          "its framework, e.g. `/** @jsxImportSource solid-js */`, or import from it.",
        ]
      : []),
    "",
    "## Commands",
    "",
    "| Command | Does |",
    "| --- | --- |",
    `| \`${run} dev\` | Dev server on http://localhost:5173; \`/\` is the devtools page |`,
    `| \`${run} build\` | Builds \`dist/\` for ${main} |`,
    ...adapters.filter((a) => a !== main).map((a) => `| \`${run} build:${a}\` | Builds \`dist/\` for ${a} |`),
    `| \`${run} typecheck\` | \`djs sync\`, then \`tsc\` |`,
    `| \`${djs} add <name> …\` | A new droplet (see below) |`,
    `| \`${djs} sync\` | Rewrites \`.droplets/\` (each droplet's \`./$types\`) |`,
    "",
    "## Checking your work",
    "",
    `1. \`${run} typecheck\`: types, each droplet's \`./$types\` included.`,
    `2. \`${run} build\`: also catches cross-framework imports and CSS in load modules.`,
    `3. \`${run} dev\`, then http://localhost:5173/: pick the droplet, set its props, watch it`,
    `   render. One fragment alone: http://localhost:5173/droplets/${starterName(example)}?who=Ana.`,
    "",
    "## Layout",
    "",
    "```",
    "src/droplets/<name>/",
    "  +droplet.<ext>       the component (required); flags go here",
    "  +droplet.ts          optional: `props` schema, `load`; server and browser",
    "  +droplet.server.ts   optional: `load`, `actions`, `handleError`, `entries`, `transform`; server only",
    "  +error.<ext>         optional: the error page, same framework",
    "  +droplet.script.ts   instead of a component: plain browser code, `default (data, el)`; built in",
    "src/api/**/+server.ts  API routes under /api/ (GET, POST, … exports)",
    "src/hooks.server.ts    optional: `handle`, `handleError` for every request",
    "src/env.ts             optional: environment variables (`defineEnvVars`)",
    "src/app.css            the stylesheet every droplet shares",
    "src/lib/               your code: neutral, or in a folder per framework",
    "```",
    "",
    "The folder name is the droplet's id, kebab-cased (`HelloWorld` → `hello-world`).",
    "",
    "## Flags",
    "",
    "Three literal flags decide how a droplet is delivered:",
    "",
    "| Flag | Default | Meaning |",
    "| --- | --- | --- |",
    "| `ssr` | `true` | `false`: nothing rendered on the server |",
    "| `hydrate` | `true` | `false`: no JavaScript; `\"visible\"` or `\"interactive\"`: later |",
    "| `prerender` | `false` | `true`: rendered at build for the events `entries` returns (`{ props, host }`) |",
    "",
    ...choices.frameworks.map((f) => `- ${f.label}: ${FLAGS_WHERE[f.name]}`),
    "",
    "Values must be literals (`export const ssr = !dev` is ignored, with a warning).",
    "",
    "## Data",
    "",
    "```",
    "props (query string, POST body)",
    "  → `export const props` in +droplet.ts (a Standard Schema: zod, valibot…), optional",
    "  → `load` in +droplet.server.ts ({ props, host, locals, request, … }), server only",
    "  → `load` in +droplet.ts ({ props, host, data }), server and browser",
    "  → the component's `data`",
    "```",
    "",
    "- Types come from the generated `./$types`: `DropletProps` for the component,",
    "  `LoadEvent` for the server load, `DropletLoadEvent` for the universal one.",
    "  Import them (`import type { DropletProps } from \"./$types\"`); never write",
    "  the shapes by hand.",
    "- `data` is a value when hydrating and a promise when the droplet mounts from",
    "  scratch in the browser (Lit's renderer waits for it: always a value there);",
    "  the starter droplets show the pattern for each framework.",
    "- `error(404, \"…\")` from `$droplets/server` in a load shows `+error.<ext>`;",
    "  `handleError` in `+droplet.server.ts` decides what the error page receives.",
    "- `host` is where the droplet renders (the host page, a `URL`); this server",
    "  is `droplet.url(…)`. While prerendering only `host.origin`, `host.pathname`",
    "  and `host.href` work, unless the entry gives a `host`.",
    "- Load results are inlined into the page: never return secrets.",
    "  `$droplets/env/private` and `$droplets/server` only work in server files",
    "  (`*.server.ts`, files under a `server/` folder), and server files never reach",
    "  the browser: import them from `+droplet.server.ts`, never from `+droplet.ts`.",
    "- Props, `host` and form fields come from the request: check them (a schema,",
    "  `typeof`), look request-chosen keys up with `Object.hasOwn`, never use them",
    "  to decide who may see or do what.",
    "- In the browser a relative `fetch(\"/api/…\")` reaches the host page, not this",
    "  server: build URLs with `droplet.url(\"/api/…\")` from `$droplets/drop`.",
    "- A `<form method=\"post\">` posts to the host page unless its `action` is",
    "  `actionUrl(\"name\")` from `$droplets/form` (`{{action \"name\"}}` in Handlebars):",
    "  the URL of `actions.name` in +droplet.server.ts on this server. In the browser",
    "  `actionUrl` knows the droplet only while it renders: call it as the component",
    "  sets up. Forms post natively; `enhanceDropletForm` (or the renderer's `/form`",
    "  wrapper, `data-droplets-enhance` in Handlebars) posts by fetch and updates in place.",
    "",
    "## Styles",
    "",
    "Styles belong to the component: `+droplet.<ext>`, `+error.<ext>`, the modules",
    "they import, or a `<style>` block. Never import CSS from `+droplet.ts` or",
    "`+droplet.server.ts` (or anything they import): the build fails. Every",
    "stylesheet is scoped to the droplet element, so it never restyles the host page.",
    "",
    ...choices.frameworks.map((f) => `- ${f.label}: ${STYLES_WHERE[f.name]}`),
    ...(choices.tailwind ? ["- Tailwind classes work in every droplet; `src/app.css` imports Tailwind."] : []),
    "",
    "## Adding a droplet",
    "",
    "Use `djs add`; it writes the folder and its `./$types`. Without a terminal, pass",
    "everything and `--yes`:",
    "",
    "```bash",
    `${djs} add <name> --framework ${example.name} --target full --with server,error --yes`,
    "```",
    "",
    "| Option | Values |",
    "| --- | --- |",
    "| `--framework` | `svelte`, `vue`, `react`, `preact`, `solid`, `hono-jsx`, `handlebars`, `lit` (one not in vite.config is installed and added), or `script` (built in) |",
    "| `--target` | `full` (server-rendered, then interactive), `ssr` (no JavaScript), `client` (browser only), `ssg` (prerendered) |",
    "| `--hydrate` | `always`, `visible`, `interactive`, `none`: only to override the target |",
    "| `--with` | `server`, `universal`, `error`, `css`, comma-separated |",
    "",
    "## Do not",
    "",
    "- edit `.droplets/`: `vite` and `djs sync` write it;",
    "- import another framework, or its components, into a droplet;",
    "- import CSS from `+droplet.ts` or `+droplet.server.ts`;",
    "- compute a flag: flags are literals, read before anything is compiled.",
    "",
  ];
  return lines.join("\n");
}
